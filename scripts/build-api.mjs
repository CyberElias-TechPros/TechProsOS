/**
 * Bundle the serverless API into a single self-contained ESM file.
 *
 * Why: Vercel compiles `api/*.ts` with its OWN TypeScript settings (moduleResolution
 * node16/nodenext), ignoring tsconfig.server.json. Our source uses extensionless
 * relative imports, which are illegal under nodenext, so every server import failed
 * at runtime with FUNCTION_INVOCATION_FAILED — while the build still reported success.
 *
 * Bundling resolves all relative imports at build time and emits plain JavaScript, so
 * no TypeScript resolution happens in the Vercel function at all. It also removes the
 * per-request module graph walk, which cuts cold-start time.
 *
 * `pg` stays external: it is a real dependency with optional native bindings that must
 * be resolved from node_modules at runtime, not inlined.
 *
 * The bundle is written to server-dist/, NOT api/. Vercel globs the api/ directory to
 * discover functions BEFORE the build command runs, so a generated (gitignored) file
 * placed there is invisible and the deployment ends up with zero functions. api/index.mjs
 * is a small TRACKED stub that re-exports this bundle; its import is resolved after the
 * build, when the bundle exists.
 */
import { build } from 'esbuild';
import { mkdir, rm } from 'node:fs/promises';

const OUT = 'server-dist/vercel.mjs';

await mkdir('server-dist', { recursive: true });
// Remove any stale bundle so a failed build cannot ship the previous one.
await rm(OUT, { force: true });

const result = await build({
  entryPoints: ['server/vercel-entry.ts'],
  outfile: OUT,
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  // pg resolves native bindings at runtime; PGlite is dev/test-only WASM.
  external: ['pg', 'pg-native', '@electric-sql/pglite'],
  sourcemap: false,
  minify: false,
  legalComments: 'none',
  logLevel: 'warning',
  metafile: true,
  banner: {
    js: [
      '// Generated by scripts/build-api.mjs — do not edit.',
      // pg's ESM entry is CJS; give bundled requires a working require() if any dep needs it.
      "import { createRequire as __createRequire } from 'node:module';",
      'const require = __createRequire(import.meta.url);',
    ].join('\n'),
  },
});

const bytes = Object.values(result.metafile.outputs).reduce((n, o) => n + o.bytes, 0);
console.log(`API bundled: ${OUT} (${(bytes / 1024).toFixed(1)} KB)`);
