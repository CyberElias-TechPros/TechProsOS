/** IT tools inside the workspace — subnet/VLAN planner, SLA calculator, data estimator, config generator. */
import { useMemo, useState } from 'react';
import { useSessionCtx } from '../../platform/session';
import { useData } from '../../platform/store';
import { latencyClass, splitSubnets, subnetInfo, dataBurnEstimate, vlanSuggestion } from '../../platform/net';
import { addBusinessMinutes, DEFAULT_SLA_TARGETS } from '../../platform/sla';
import { copyText, downloadText, fmtDateTime } from '../../platform/util';
import { PageHead, Table, Tabs, toast, Badge } from '../../components/ui';
import { Icon } from '../../components/icons';

function SubnetPlanner() {
  const [cidr, setCidr] = useState('10.10.0.0/16');
  const [n, setN] = useState(8);
  const info = useMemo(() => subnetInfo(cidr), [cidr]);
  const parts = useMemo(() => (info ? splitSubnets(cidr, n) : []), [cidr, info, n]);
  const vlans = info ? vlanSuggestion(parseInt(cidr.split('/')[1] ?? '24', 10) || 24) : [];
  return (
    <div className="stack">
      <div className="row" style={{ gap: 8 }}>
        <input className="input mono" style={{ maxWidth: 220 }} value={cidr} onChange={e => setCidr(e.target.value)} aria-label="CIDR" placeholder="10.0.0.0/16" />
        <select className="select" style={{ width: 170 }} value={n} onChange={e => setN(+e.target.value)} aria-label="Split count">
          {[2, 4, 8, 16, 32].map(x => <option key={x} value={x}>Split into {x}</option>)}
        </select>
      </div>
      {!info ? <div className="note">Enter a valid IPv4 CIDR notation.</div> : (
        <>
          <div className="grid-4">
            {[['Network', info.network], ['Broadcast', info.broadcast], ['Mask', info.mask], ['Usable hosts', info.hosts.toLocaleString()]].map(([k, v]) => (
              <div key={k} className="card flat card-tight"><div className="lbl">{k}</div><div className="mono b">{v}</div></div>
            ))}
          </div>
          {parts.length > 0 && <div className="note info">Splitting into {parts.length} children of {info.hosts + 2} → allocates /{parts[0].cidr.split('/')[1]} each.</div>}
          {parts.length > 0 && (
            <Table head={['Child', 'First host', 'Last host', 'Hosts', 'Suggested use']}>
              {parts.map((p, i) => (
                <tr key={p.cidr}>
                  <td className="mono b">{p.cidr}</td>
                  <td className="mono sm">{p.firstHost}</td>
                  <td className="mono sm">{p.lastHost}</td>
                  <td className="num">{p.hosts.toLocaleString()}</td>
                  <td className="sm muted">{vlans[i % vlans.length] ? `VLAN ${vlans[i % vlans.length].vlan} — ${vlans[i % vlans.length].name}` : ''}</td>
                </tr>
              ))}
            </Table>
          )}
        </>
      )}
    </div>
  );
}

function SlaPlanner() {
  const [priority, setPriority] = useState<keyof typeof DEFAULT_SLA_TARGETS>('critical');
  const [from, setFrom] = useState(() => {
    const d = new Date(); d.setHours(9, 40, 0, 0); return d.toISOString();
  });
  const t = DEFAULT_SLA_TARGETS[priority];
  const cal = { workStartHour: 8, workEndHour: 18, workDays: [1, 2, 3, 4, 5], holidays: [] as string[] };
  const respDue = addBusinessMinutes(from, t.response, cal);
  const resDue = addBusinessMinutes(from, t.resolve, cal);
  return (
    <div className="stack">
      <div className="row" style={{ gap: 8 }}>
        <select className="select" style={{ width: 180 }} value={priority} onChange={e => setPriority(e.target.value as typeof priority)} aria-label="Priority">
          {(['critical', 'high', 'medium', 'low'] as const).map(p => <option key={p} value={p}>{p}</option>)}
        </select>
        <input className="input" style={{ maxWidth: 240 }} type="datetime-local" value={from.slice(0, 16)} onChange={e => setFrom(new Date(e.target.value).toISOString())} aria-label="Raised at" />
      </div>
      <div className="grid-2">
        <div className="card flat pad-lg"><div className="lbl">First response due</div><b style={{ fontSize: 18 }}>{fmtDateTime(respDue)}</b><div className="xs muted">{t.response} business minutes</div></div>
        <div className="card flat pad-lg"><div className="lbl">Resolution due</div><b style={{ fontSize: 18 }}>{fmtDateTime(resDue)}</b><div className="xs muted">{t.resolve} business minutes</div></div>
      </div>
      <p className="xs muted">Calendar: Mon–Fri 08:00–18:00 WAT (stored as UTC, so timezone travel is safe).</p>
    </div>
  );
}

function ConfigGen() {
  const [wanIp, setWanIp] = useState('41.223.144.5/30');
  const [lan, setLan] = useState('192.168.44.1/24');
  const [ssid, setSsid] = useState('TechPros-Staff');
  const cfg = useMemo(() => {
    const ip = subnetInfo(wanIp); void ip;
    return [
      '# Generated by TechPros One — MikroTik baseline for a single-site LAN',
      '# Review with a certified engineer before applying to production.',
      '',
      '/interface bridge add name=LAN-Bridge',
      `/ip address add address=${lan} interface=LAN-Bridge comment="LAN gateway"`,
      `/ip address add address=${wanIp} interface=ether1 comment="WAN uplink"`,
      '',
      `/ip pool add name=dhcp-lan ranges=${lan.split('.').slice(0, 3).join('.')}.50-${lan.split('.').slice(0, 3).join('.')}.250`,
      '/ip dhcp-server add interface=LAN-Bridge address-pool=dhcp-lan name=lan-dhcp',
      '/ip dhcp-server network add address=192.168.44.0/24 gateway=192.168.44.1 dns-server=192.168.44.1',
      '',
      '/ip firewall nat add chain=srcnat out-interface=ether1 action=masquerade comment="NAT LAN→WAN"',
      '/ip firewall filter add chain=input connection-state=established,related action=accept',
      '/ip firewall filter add chain=input in-interface=ether1 action=drop comment="Drop unsolicited WAN"',
      `/caps-man wireless security add name=staff-auth authentication-types=wpa2-psk passphrase=ChangeMe123`,
      `# SSID suggestion: "${ssid}"`,
    ].join('\n');
  }, [wanIp, lan, ssid]);
  return (
    <div className="stack">
      <div className="row" style={{ gap: 8 }}>
        <label className="lbl">WAN <input className="input mono" value={wanIp} onChange={e => setWanIp(e.target.value)} style={{ width: 150 }} /></label>
        <label className="lbl">LAN GW <input className="input mono" value={lan} onChange={e => setLan(e.target.value)} style={{ width: 150 }} /></label>
        <label className="lbl">SSID <input className="input" value={ssid} onChange={e => setSsid(e.target.value)} style={{ width: 170 }} /></label>
      </div>
      <pre className="mono xs" style={{ background: 'var(--ink)', color: '#c8d7ec', borderRadius: 10, padding: 16, overflow: 'auto', lineHeight: 1.65, margin: 0 }}>{cfg}</pre>
      <div className="row">
        <button className="btn secondary sm" onClick={() => { copyText(cfg); toast('Config copied to clipboard'); }}><Icon name="check" size={13} /> Copy</button>
        <button className="btn secondary sm" onClick={() => downloadText('mikrotik-baseline.rsc', cfg)}><Icon name="download" size={13} /> Download .rsc</button>
        <Badge tone="outline">Review before use</Badge>
      </div>
    </div>
  );
}

function Bandwidth() {
  const [video, setVideo] = useState(2); const [meetings, setMeetings] = useState(2); const [users, setUsers] = useState(45);
  const est = dataBurnEstimate({ videoHoursPerDay: video, meetingHoursPerDay: meetings, users });
  const lc = latencyClass(28);
  return (
    <div className="stack">
      <div className="row" style={{ gap: 10 }}>
        <label className="lbl">Users <input className="input" type="number" style={{ width: 90 }} value={users} onChange={e => setUsers(+e.target.value)} /></label>
        <label className="lbl">Video hr/day <input className="input" type="number" style={{ width: 90 }} value={video} onChange={e => setVideo(+e.target.value)} /></label>
        <label className="lbl">Meetings hr/day <input className="input" type="number" style={{ width: 90 }} value={meetings} onChange={e => setMeetings(+e.target.value)} /></label>
      </div>
      <div className="row" style={{ gap: 22 }}>
        <div><div className="lbl">Monthly estimate</div><b style={{ fontSize: 28 }}>{est.gbPerMonth.toLocaleString()} GB</b></div>
        <div><div className="lbl">Reference latency</div><b style={{ fontSize: 28 }}>28 ms</b><span className="muted sm"> ({lc.label})</span><p className="xs muted" style={{ maxWidth: '36ch' }}>{lc.advice}</p></div>
      </div>
      <p className="xs muted">{est.note}</p>
    </div>
  );
}

export default function Tools() {
  const { tenant } = useSessionCtx();
  useData(s => s.data);
  const [tab, setTab] = useState('subnet');
  return (
    <div style={{ maxWidth: 1030 }} className="stack">
      <PageHead crumbs={[tenant.name, 'IT tools']} title="IT tools"
        sub="The calculators and generators our own engineers use. Everything computes locally." />
      <div className="card pad-lg stack no-print">
        <Tabs tabs={[['subnet', 'Subnet & VLAN planner'], ['sla', 'SLA calculator'], ['config', 'MikroTik config generator'], ['data', 'Bandwidth estimator']]} value={tab} onChange={setTab} />
      </div>
      <div className="card pad-lg">
        {tab === 'subnet' && <SubnetPlanner />}
        {tab === 'sla' && <SlaPlanner />}
        {tab === 'config' && <ConfigGen />}
        {tab === 'data' && <Bandwidth />}
      </div>
    </div>
  );
}
